public class OperatorLab { 
   public static void main(String[] args) 
    { 
        int a = 10; 
        int b = 3; 
        System.out.println(a + b); 
        System.out.println(a - b); 
        System.out.println(a * b); 
        System.out.println(a / b); 
        System.out.println(a % b);

        int number = 17;

        System.out.println(number % 2);
    } 
}